// 考点级特例（code → 摘要，覆盖章节级）
const POINT_SUMMARIES = {};

async function main() {
  const subjects = await prisma.subject.findMany();
  let updated = 0;
  for (const s of subjects) {
    const chapterMap = CHAPTER_SUMMARIES[s.name];
    if (!chapterMap) continue;
    const points = await prisma.knowledgePoint.findMany({
      where: { chapter: { subjectId: s.id }, level: 2 },
      include: { chapter: true },
    });
    for (const p of points) {
      const summary = POINT_SUMMARIES[p.code] || chapterMap[p.chapter.name];
      if (!summary) continue;
      if (p.summary === summary) continue;
      await prisma.knowledgePoint.update({ where: { id: p.id }, data: { summary } });
      updated++;
    }
    console.log(`📚 ${s.name}: 已写入 ${points.filter((p) => POINT_SUMMARIES[p.code] || chapterMap[p.chapter.name]).length}/${points.length} 个考点摘要`);
  }
  console.log(`✅ 共更新 ${updated} 个考点`);
  await prisma.$disconnect();
}

await main();
